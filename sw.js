self.addEventListener("install", e => {
  // skipWaiting before the kits so a new build takes over straight away
  // rather than sitting behind a thousand shirt downloads
  /* DE-DUPLICATED BEFORE IT GOES IN, because ASSETS is assembled from several
     lists written by four different tools plus the hand-typed ones, and they
     legitimately name the same file more than once. Counted: 18 of the 31
     crests in ERECRESTS are also in CLUB_CRESTS, 20 slugs in CAREER_LOGOS
     appear twice or more (lille and santos three times each), and the generated
     pool files repeat the eleven still typed into EXTRA_ASSETS. On the list
     this landed against, 653 entries were 511 distinct requests, so 142 of them
     were the same URL asked for twice.
     IT IS FATAL, AND IT HAS BEEN WATCHED. Run in headless Edge over localhost,
     which is a secure context and so has the real Cache API:

       addAll(["a.txt","b.txt"])          resolved, and read back 2 entries
       addAll(["a.txt","b.txt","a.txt"])  threw InvalidStateError,
                                          "Cache.addAll(): duplicate requests",
                                          and read back 0 entries

     It rejects the whole batch, not the repeated item. So on the list this
     landed against, addAll rejected every time, the .then holding skipWaiting
     never ran, and the cache stayed empty. Every install of this app has been
     running network only and the offline story has never once worked, which
     nothing reported because a service worker that throws inside waitUntil does
     it silently.

     This line is therefore load bearing rather than a tidy-up, and the reason
     it lives at the call site is that each list upstream goes on being a
     straight answer to its own question, none of them has to know what the
     others hold, and the install asks for each file exactly once. */
  e.waitUntil(caches.open(CACHE)
    .then(c => c.addAll([...new Set(ASSETS)]).then(() => self.skipWaiting())));
});

self.addEventListener("activate", e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

/* APP FEEL (_plans/audit-app-feel.md):
   - only a good answer goes in the cache. It used to store whatever came back,
     so one 404 or 500 (or a captive-portal page) overwrote the good copy and
     was then what the phone served offline.
   - the app page itself is asked for with no-cache, so the HTTP cache cannot
     hand back yesterday's index.html: a new version lands on the next open.
   - and if the network sits there (the pub's wifi that is connected but
     dead) the cached page is shown after 4 seconds instead of a white screen
     until the request gives up; the network copy still lands in the cache. */
const NAV_WAIT = 4000;
const keep = (req, res) => {
  if (res && res.ok && (res.type === "basic" || res.type === "cors")) {
    const copy = res.clone();
    caches.open(CACHE).then(c => c.put(req, copy)).catch(() => {});
  }
  return res;
};
const cached = req => caches.match(req, { ignoreSearch: true });

self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  if (req.mode !== "navigate") {
    e.respondWith(fetch(req).then(res => keep(req, res))
      .catch(() => cached(req).then(hit => hit || Response.error())));
    return;
  }
  /* A sport never falls back to BALL's page: that would open BALL inside its own sport switch */
  const page = () => cached(req).then(hit => hit || (/\/(dart|racket)\//.test(new URL(req.url).pathname) ? null : caches.match("index.html")));
  e.respondWith(new Promise(resolve => {
    let done = false;
    const give = r => { if (!done && r) { done = true; resolve(r); } };
    const slow = setTimeout(() => page().then(give), NAV_WAIT);
    fetch(req.url, { cache: "no-cache", credentials: "same-origin" })
      .then(res => { clearTimeout(slow); give(keep(req, res)); })
      .catch(() => { clearTimeout(slow); page().then(hit => give(hit || Response.error())); });
  }));
});

/* PUSH REMINDERS (assets/push/push.js; the sender is supabase/functions/push-send). The payload is JSON:
   {title, body, url, tag, icon, badge}. One a day at most is the server's promise (015_push.sql, push_plan);
   here it is shown as it comes, with BALL's own icon, and a tap brings an open BALL to the front or opens one.
   A push with no readable payload still shows something: a push the phone received and never showed makes
   Chrome show its own "This site has been updated in the background" instead. */
self.addEventListener("push", e => {
  let d = {};
  try{ d = e.data ? e.data.json() : {}; }catch(x){ try{ d = { body: e.data ? e.data.text() : "" }; }catch(y){ d = {}; } }
  const o = { body: d.body || "", icon: d.icon || "icons/icon-192.png", badge: d.badge || "icons/icon-192.png",
    tag: d.tag || "ball", renotify: false, data: { url: d.url || "./" } };
  e.waitUntil(self.registration.showNotification(d.title || "BALL", o));
});
self.addEventListener("notificationclick", e => {
  e.notification.close();
  const scope = self.registration.scope;
  let url = scope;
  try{ url = new URL((e.notification.data && e.notification.data.url) || "./", scope).href; }catch(x){}
  e.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then(list => {
    const open = list.find(c => c.url.indexOf(scope) === 0 && "focus" in c);
    if(open) return open.focus();
    return self.clients.openWindow ? self.clients.openWindow(url) : null;
  }));
});
