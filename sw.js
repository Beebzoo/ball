self.addEventListener("install", e => {
  // skipWaiting before the kits so a new build takes over straight away
  // rather than sitting behind a thousand shirt downloads
  /* DE-DUPLICATED BEFORE IT GOES IN, because ASSETS is assembled from several
     lists written by four different tools plus the hand-typed ones, and they
     legitimately name the same file more than once. Counted: 18 of the 31
     crests in ERECRESTS are also in CLUB_CRESTS, 20 slugs in CAREER_LOGOS
     appear twice or more (lille and santos three times each), and the generated
     pool files repeat the eleven still typed into EXTRA_ASSETS. On the list
     this landed against, 653 entries were 511 distinct requests, so 142 of them
     were the same URL asked for twice.
     IT IS FATAL, AND IT HAS BEEN WATCHED. Run in headless Edge over localhost,
     which is a secure context and so has the real Cache API:

       addAll(["a.txt","b.txt"])          resolved, and read back 2 entries
       addAll(["a.txt","b.txt","a.txt"])  threw InvalidStateError,
                                          "Cache.addAll(): duplicate requests",
                                          and read back 0 entries

     It rejects the whole batch, not the repeated item. So on the list this
     landed against, addAll rejected every time, the .then holding skipWaiting
     never ran, and the cache stayed empty. Every install of this app has been
     running network only and the offline story has never once worked, which
     nothing reported because a service worker that throws inside waitUntil does
     it silently.

     This line is therefore load bearing rather than a tidy-up, and the reason
     it lives at the call site is that each list upstream goes on being a
     straight answer to its own question, none of them has to know what the
     others hold, and the install asks for each file exactly once. */
  e.waitUntil(caches.open(CACHE)
    .then(c => c.addAll([...new Set(ASSETS)]).then(() => self.skipWaiting())));
});

self.addEventListener("activate", e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", e => {
  if (e.request.method !== "GET") return;
  e.respondWith(
    fetch(e.request)
      .then(res => {
        const copy = res.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true })
        .then(hit => hit || caches.match("index.html")))
  );
});
